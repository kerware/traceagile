-- ADR-0026 serveur d'exécution : jetons, jobs, tests, événements, artefacts, outils, dépôts Git

create table tokens (
    id             varchar(20)  primary key,
    label          varchar(120) not null,
    token_hash     varchar(64)  not null unique,
    webhook_secret varchar(80)  not null,
    hint           varchar(8)   not null,
    created_at     timestamp with time zone not null,
    last_used_at   timestamp with time zone,
    revoked_at     timestamp with time zone
);

create table jobs (
    id              varchar(20)  primary key,
    token_id        varchar(20)  not null references tokens (id),
    run_id          varchar(120) not null,
    project         varchar(40),
    campaign        varchar(40),
    environment     varchar(60),
    build_version   varchar(60),
    repository_url  varchar(500),
    branch          varchar(200),
    callback_url    varchar(500) not null,
    base_url        varchar(500) not null,
    status          varchar(20)  not null,
    agent           varchar(80),
    timeout_minutes int          not null,
    parallelism     int          not null,
    retry_failed    int          not null,
    submitted_at    timestamp with time zone not null,
    started_at      timestamp with time zone,
    ended_at        timestamp with time zone,
    total           int          not null default 0,
    passed          int          not null default 0,
    failed          int          not null default 0,
    errored         int          not null default 0,
    skipped         int          not null default 0,
    error_message   varchar(2000),
    constraint uk_jobs_run unique (token_id, run_id)
);
create index ix_jobs_submitted on jobs (submitted_at);

create table job_tests (
    id              bigint generated by default as identity primary key,
    job_id          varchar(20)  not null references jobs (id) on delete cascade,
    position        int          not null,
    execution_id    varchar(80)  not null,
    test_key        varchar(40)  not null,
    technique       varchar(30),
    framework       varchar(60),
    path            varchar(500),
    test_identifier varchar(500),
    gherkin_source  clob,
    parameters_json clob,
    status          varchar(20)  not null,
    attempts        int          not null default 0,
    duration_ms     bigint,
    message         varchar(4000),
    started_at      timestamp with time zone,
    ended_at        timestamp with time zone,
    metrics_json    varchar(2000)
);
create index ix_job_tests_job on job_tests (job_id);

create table job_events (
    id         bigint generated by default as identity primary key,
    job_id     varchar(20) not null references jobs (id) on delete cascade,
    event_json clob        not null,
    created_at timestamp with time zone not null
);
create index ix_job_events_job on job_events (job_id);

create table artifacts (
    job_id       varchar(20)  not null references jobs (id) on delete cascade,
    name         varchar(200) not null,
    content_type varchar(100) not null,
    kind         varchar(30)  not null,
    execution_id varchar(80),
    size_bytes   bigint       not null,
    primary key (job_id, name)
);

create table tool_installs (
    tool_id    varchar(40) primary key,
    status     varchar(20) not null,
    version    varchar(80),
    started_at timestamp with time zone,
    ended_at   timestamp with time zone,
    message    varchar(2000),
    log_file   varchar(300)
);

create table git_credentials (
    host       varchar(200) primary key,
    username   varchar(120) not null,
    secret     varchar(500) not null,
    updated_at timestamp with time zone not null
);
